"""Helper class for handle symmetric assemblies."""
from pyrsistent import v
from scipy.spatial.transform import Rotation
import functools as fn
import torch
import string
import logging
import numpy as np

from zeus_rfdiffusion.inference.symmetry_groups import (
    TETRAHEDRAL_ROTATIONS,
    OCTAHEDRAL_ROTATIONS,
    ICOSAHEDRAL_ROTATIONS,
)

format_rots = lambda r: torch.tensor(r).float()


# Hardcoded rotation groups, indexed by name. Replaces the old npz-based
# loader. Matrices are numpy float64; we convert to torch tensors on use.
_POINTGROUP_MATRICES = {
    "tetrahedral": TETRAHEDRAL_ROTATIONS,
    "octahedral":  OCTAHEDRAL_ROTATIONS,
    "icosahedral": ICOSAHEDRAL_ROTATIONS,
}

T3_ROTATIONS = [
    torch.Tensor([
        [ 1.,  0.,  0.],
        [ 0.,  1.,  0.],
        [ 0.,  0.,  1.]]).float(),
    torch.Tensor([
        [-1., -0.,  0.],
        [-0.,  1.,  0.],
        [-0.,  0., -1.]]).float(),
    torch.Tensor([
        [-1.,  0.,  0.],
        [ 0., -1.,  0.],
        [ 0.,  0.,  1.]]).float(),
    torch.Tensor([
        [ 1.,  0.,  0.],
        [ 0., -1.,  0.],
        [ 0.,  0., -1.]]).float(),
]

saved_symmetries = ['tetrahedral', 'octahedral', 'icosahedral']

class SymGen:

    def __init__(self, global_sym, recenter, radius, model_only_neighbors=False,
                 diffusion_mode='whole_assembly', anchor_radius=None):
        self._log = logging.getLogger(__name__)
        self._recenter = recenter
        self._radius = radius
        # anchor_radius can be a scalar (→ pivot along +x) or a 3-vector
        # (→ used as pivot directly, e.g. off-axis for polyhedral groups).
        if anchor_radius is None:
            anchor_pivot = [float(radius), 0.0, 0.0]
        elif hasattr(anchor_radius, '__len__') and not isinstance(anchor_radius, str):
            anchor_pivot = [float(v) for v in anchor_radius]
            assert len(anchor_pivot) == 3, f"anchor_radius vector must be length 3, got {len(anchor_pivot)}"
        else:
            anchor_pivot = [float(anchor_radius), 0.0, 0.0]
        self._anchor_pivot = anchor_pivot
        self._diffusion_mode = diffusion_mode
        self._model_only_neighbors = bool(model_only_neighbors)

        if global_sym.lower().startswith('c'):
            # Cyclic symmetry
            if not global_sym[1:].isdigit():
                raise ValueError(f'Invalid cyclic symmetry {global_sym}')
            self._log.info(
                f'Initializing cyclic symmetry order {global_sym[1:]}.')
            self._init_cyclic(int(global_sym[1:]))
            self.apply_symmetry = self._apply_cyclic

        elif global_sym.lower().startswith('d'):
            # Dihedral symmetry
            if not global_sym[1:].isdigit():
                raise ValueError(f'Invalid dihedral symmetry {global_sym}')
            self._log.info(
                f'Initializing dihedral symmetry order {global_sym[1:]}.')
            self._init_dihedral(int(global_sym[1:]))
            # Applied the same way as cyclic symmetry
            self.apply_symmetry = self._apply_cyclic

        elif global_sym.lower() == 't3':
            # Tetrahedral (T3) symmetry
            self._log.info('Initializing T3 symmetry order.')
            self.sym_rots = T3_ROTATIONS
            self.order = 4
            # Applied the same way as cyclic symmetry
            self.apply_symmetry = self._apply_cyclic

        elif global_sym.lower() in _POINTGROUP_MATRICES:
            # Full polyhedral point groups: tetrahedral (12 subunits),
            # octahedral (24), icosahedral (60). All three share a common
            # init + apply path. The apply path supports radius/recenter
            # placement (same as the old _apply_octahedral) for all three.
            name = global_sym.lower()
            self._log.info(
                f'Initializing {name} symmetry ({len(_POINTGROUP_MATRICES[name])} subunits).')
            self._init_pointgroup(name)
            if self._model_only_neighbors:
                # Replace the full polyhedral group with the cyclic subgroup
                # generated by the smallest-angle rotation. This instantiates
                # only the ASU + its immediate neighbors around one C_n axis:
                #   tetrahedral (T, C3 axis)  → 3 subunits (ASU + 2 neighbors)
                #   octahedral  (O, C4 axis)  → 4 subunits (ASU + 3 neighbors)
                #   icosahedral (I, C5 axis)  → 5 subunits (ASU + 4 neighbors)
                # Intended for null-mode generation of a local patch of the
                # assembly. Restricted mode also works (subgroup is a valid
                # cyclic group) but was not the original design intent.
                self._reduce_to_neighbors_subgroup()
                self._log.info(
                    f'model_only_neighbors: reduced to C{self.order} subgroup '
                    f'({self.order} subunits).')
            self.apply_symmetry = self._apply_pointgroup
        else:
            raise ValueError(f'Unrecognized symmetry {global_sym}')

        self.res_idx_procesing = fn.partial(
            self._lin_chainbreaks, num_breaks=self.order)

        # Build the g⁻¹h permutation table for pair-matrix tiling.
        # Works for cyclic (circulant), dihedral, and polyhedral groups.
        from zeus_rfdiffusion.util_module import build_group_permutations
        self.perm_table, _ = build_group_permutations(self.sym_rots)

        # When attention saving is enabled, persist the perm_table (and the raw
        # rotation matrices) once so the analysis script can compute tiled
        # references without needing to reconstruct the symmetry.
        import os as _os
        if _os.getenv("RFDIFF_SAVE_ATTN", "0") == "1":
            attn_dir = _os.getenv("RFDIFF_ATTN_DIR")
            if attn_dir:
                _os.makedirs(attn_dir, exist_ok=True)
                torch.save(self.perm_table, _os.path.join(attn_dir, "perm_table.pt"))
                _rots_stack = torch.stack([
                    r.float() if isinstance(r, torch.Tensor)
                    else torch.tensor(r, dtype=torch.float32)
                    for r in self.sym_rots
                ])
                torch.save(_rots_stack, _os.path.join(attn_dir, "sym_rots.pt"))

        # Stack sym_rots into a (S, 3, 3) tensor for SE3 tiling.
        # Identity is at index 0 (moved there by each _init_* method).
        self.sym_rots_tensor = torch.stack([
            r.float() if isinstance(r, torch.Tensor)
            else torch.tensor(r, dtype=torch.float32)
            for r in self.sym_rots
        ])

        # Pivot-on-axis (stabilizer) check for modes that place subunits via a
        # fixed pivot. If any non-identity R_k fixes P (i.e. R_k @ P ≈ P), that
        # slot's centroid will collapse onto the ASU and atoms overlap.
        if self._diffusion_mode in ('offset_symmetric', 'anchored'):
            if self._diffusion_mode == 'anchored':
                P_vec = self._anchor_pivot
            else:
                P_vec = [float(self._radius), 0.0, 0.0]
            if any(v != 0 for v in P_vec):
                P = torch.tensor(P_vec, dtype=torch.float32)
                offenders = []
                for k in range(1, self.order):
                    R_k = self.sym_rots[k]
                    R_k = R_k.float() if isinstance(R_k, torch.Tensor) else torch.tensor(
                        R_k, dtype=torch.float32)
                    if torch.allclose(R_k @ P, P, atol=1e-5):
                        offenders.append(k)
                if offenders:
                    raise ValueError(
                        f"Pivot P={P_vec} is fixed by {len(offenders)} "
                        f"non-identity rotations (indices {offenders}) of group "
                        f"'{global_sym}'. Orbit collapses to "
                        f"{self.order // (len(offenders) + 1)} distinct sites — "
                        f"subunits will overlap. Pick a generic pivot direction "
                        f"(off all rotation axes)."
                    )

    #####################
    ## Cyclic symmetry ##
    #####################
    def _init_cyclic(self, order):
        sym_rots = []
        for i in range(order):
            deg = i * 360.0 / order
            r = Rotation.from_euler('z', deg, degrees=True)
            sym_rots.append(format_rots(r.as_matrix()))
        self.sym_rots = sym_rots
        self.order = order

    def _apply_cyclic(self, coords_in, seq_in):
        coords_out = torch.clone(coords_in)
        seq_out = torch.clone(seq_in)
        if seq_out.shape[0] % self.order != 0:
            raise ValueError(
                f'Sequence length must be divisble by {self.order}')
        subunit_len = seq_out.shape[0] // self.order

        if self._diffusion_mode == 'offset_symmetric':
            # Rotate each copy around a fixed pivot P = [radius, 0, 0]:
            #   x_k = R_k @ (asu - P) + P.
            # ASU is re-centered at the origin each call, pinning the subunit
            # centroid orbit at exactly |P|.
            asu = coords_out[:subunit_len]
            asu_center = torch.mean(asu[:, 1, :], dim=0)
            asu = asu - asu_center[None, None, :]
            P = torch.tensor([self._radius, 0., 0.],
                             dtype=asu.dtype, device=asu.device)
            for i in range(self.order):
                start_i = subunit_len * i
                end_i = subunit_len * (i + 1)
                R_i = self.sym_rots[i].to(asu.device).to(asu.dtype)
                shift = P - R_i @ P  # (I - R_i) @ P
                coords_out[start_i:end_i] = (
                    torch.einsum('bnj,kj->bnk', asu, R_i)
                    + shift[None, None, :]
                )
                seq_out[start_i:end_i] = seq_out[:subunit_len]
        elif self._diffusion_mode == 'anchored':
            # Anchored: center ASU, translate centroid to P = [anchor_radius,0,0],
            # rotate each copy around origin, then translate the whole assembly
            # so the ASU (slot 0) lands at the origin.
            #   x_k = R_k @ (asu' + P) - P
            asu = coords_out[:subunit_len]
            asu_center = torch.mean(asu[:, 1, :], dim=0)
            asu = asu - asu_center[None, None, :]
            P = torch.tensor(self._anchor_pivot,
                             dtype=asu.dtype, device=asu.device)
            placed = asu + P[None, None, :]
            for i in range(self.order):
                start_i = subunit_len * i
                end_i = subunit_len * (i + 1)
                R_i = self.sym_rots[i].to(asu.device).to(asu.dtype)
                coords_out[start_i:end_i] = torch.einsum(
                    'bnj,kj->bnk', placed, R_i)
                seq_out[start_i:end_i] = seq_out[:subunit_len]
            # Slot 0 centroid after rotation = I @ P = P. Subtract to land ASU
            # at origin.
            coords_out = coords_out - P[None, None, :]
        else:
            # Whole-assembly mode: pure rotation around origin, no centering.
            # The model determines the effective radius through its own COM drift.
            for i in range(self.order):
                start_i = subunit_len * i
                end_i = subunit_len * (i + 1)
                coords_out[start_i:end_i] = torch.einsum(
                    'bnj,kj->bnk', coords_out[:subunit_len], self.sym_rots[i])
                seq_out[start_i:end_i] = seq_out[:subunit_len]
        return coords_out, seq_out

    def _lin_chainbreaks(self, num_breaks, res_idx, offset=None):
        #number of breaks = symmetry order. res_idx = 1...n
        assert res_idx.ndim == 2
        res_idx = torch.clone(res_idx)
        subunit_len = res_idx.shape[-1] // num_breaks
        chain_delimiters = []
        chain_labels_list = list(string.ascii_uppercase) + [a+b for a in
                string.ascii_uppercase for b in string.ascii_uppercase]

        if offset is None:
            offset = res_idx.shape[-1]
        for i in range(num_breaks):
            start_i = subunit_len * i
            end_i = subunit_len * (i+1)
            chain_delimiters.extend([chain_labels_list[i]] * subunit_len)
            res_idx[:, start_i:end_i] = res_idx[:, start_i:end_i] + offset * (i+1)
        return res_idx, chain_delimiters

    #######################
    ## Dihedral symmetry ##
    #######################
    def _init_dihedral(self, order):
        sym_rots = []
        flip = Rotation.from_euler('x', 180, degrees=True).as_matrix()
        for i in range(order):
            deg = i * 360.0 / order
            rot = Rotation.from_euler('z', deg, degrees=True).as_matrix()
            sym_rots.append(format_rots(rot))
            rot2 = flip @ rot
            sym_rots.append(format_rots(rot2))
        self.sym_rots = sym_rots
        self.order = order * 2

    ##############################
    ## Polyhedral point groups ##
    ##############################
    def _init_pointgroup(self, name):
        """Initialize from a hardcoded polyhedral rotation group.

        Args:
            name: one of 'tetrahedral' (12), 'octahedral' (24), 'icosahedral' (60).

        Sets self.sym_rots to a list of (3, 3) float32 torch tensors with
        the identity as the first element.
        """
        assert name in _POINTGROUP_MATRICES, (
            f"{name} not in {list(_POINTGROUP_MATRICES.keys())}")

        mats = _POINTGROUP_MATRICES[name]
        self.sym_rots = [torch.tensor(M, dtype=torch.float32) for M in mats]
        self.order = len(self.sym_rots)

        # Move identity to index 0 (the hardcoded matrices are not sorted).
        if not torch.allclose(self.sym_rots[0], torch.eye(3), atol=1e-5):
            for i, R in enumerate(self.sym_rots):
                if torch.allclose(R, torch.eye(3), atol=1e-5):
                    self.sym_rots = [self.sym_rots.pop(i)] + self.sym_rots
                    break
            assert torch.allclose(self.sym_rots[0], torch.eye(3), atol=1e-5), (
                f"No identity found in {name} rotation set")
        assert len(self.sym_rots) == self.order

    def _reduce_to_neighbors_subgroup(self):
        """Replace self.sym_rots with the cyclic subgroup <R> where R is the
        minimum-angle non-identity rotation in the current group.

        For the supported polyhedral groups the min-angle axis is:
            tetrahedral → C3 (120°) → |<R>| = 3
            octahedral  → C4 (90°)  → |<R>| = 4
            icosahedral → C5 (72°)  → |<R>| = 5
        The resulting subgroup is ordered as [I, R, R^2, ..., R^(n-1)] so that
        subunit index i corresponds to rotation R^i around a single axis.
        """
        rots_np = np.stack([
            r.detach().cpu().numpy() if isinstance(r, torch.Tensor) else np.asarray(r)
            for r in self.sym_rots
        ]).astype(np.float64)

        # Identity is at index 0; find the smallest-angle non-identity rotation.
        angles = np.array([
            np.linalg.norm(Rotation.from_matrix(R).as_rotvec()) for R in rots_np
        ])
        angles[0] = np.inf  # skip identity
        R_gen = rots_np[int(np.argmin(angles))]

        # Enumerate <R>: identity, R, R^2, ... until we return to identity.
        subgroup = [np.eye(3)]
        Rk = R_gen.copy()
        for _ in range(len(rots_np)):  # bounded by |G|
            if np.allclose(Rk, np.eye(3), atol=1e-5):
                break
            subgroup.append(Rk)
            Rk = Rk @ R_gen
        else:
            raise RuntimeError(
                "Failed to close cyclic subgroup within |G| iterations — "
                "min-angle rotation is not a group element?"
            )

        self.sym_rots = [torch.tensor(M, dtype=torch.float32) for M in subgroup]
        self.order = len(self.sym_rots)

    def _apply_pointgroup(self, coords_in, seq_in):
        """Apply a polyhedral point group to the asymmetric subunit.

        Works for tetrahedral, octahedral, and icosahedral. Behavior mirrors
        _apply_cyclic:
          - diffusion_mode='subunit':  each copy is placed onto the orbit of
            [radius, 0, 0] under the group (subunits lie on a sphere of
            radius self._radius).
          - diffusion_mode='whole_assembly' (default): pure rotation around
            origin, no radial placement. The model determines the effective
            radius through its own COM drift.
        """
        coords_out = torch.clone(coords_in)
        seq_out = torch.clone(seq_in)
        if seq_out.shape[0] % self.order != 0:
            raise ValueError(
                f'Sequence length must be divisble by {self.order}')
        subunit_len = seq_out.shape[0] // self.order

        if self._diffusion_mode == 'offset_symmetric':
            # Rotate each copy around a fixed pivot P = [radius, 0, 0]:
            #   x_k = R_k @ (asu - P) + P.
            # ASU is re-centered at the origin each call.
            asu = coords_out[:subunit_len]
            asu_center = torch.mean(asu[:, 1, :], dim=0)
            asu = asu - asu_center[None, None, :]
            P = torch.tensor([self._radius, 0., 0.],
                             dtype=asu.dtype, device=asu.device)
            for i in range(self.order):
                start_i = subunit_len * i
                end_i = subunit_len * (i + 1)
                R_i = self.sym_rots[i].to(asu.device).to(asu.dtype)
                shift = P - R_i @ P
                coords_out[start_i:end_i] = (
                    torch.einsum('bnj,kj->bnk', asu, R_i)
                    + shift[None, None, :]
                )
                seq_out[start_i:end_i] = seq_out[:subunit_len]
        elif self._diffusion_mode == 'anchored':
            # Anchored: center ASU, translate to P = [anchor_radius,0,0], rotate
            # around origin, then shift whole assembly so ASU lands at origin.
            #   x_k = R_k @ (asu' + P) - P
            asu = coords_out[:subunit_len]
            asu_center = torch.mean(asu[:, 1, :], dim=0)
            asu = asu - asu_center[None, None, :]
            P = torch.tensor(self._anchor_pivot,
                             dtype=asu.dtype, device=asu.device)
            placed = asu + P[None, None, :]
            for i in range(self.order):
                start_i = subunit_len * i
                end_i = subunit_len * (i + 1)
                R_i = self.sym_rots[i].to(asu.device).to(asu.dtype)
                coords_out[start_i:end_i] = torch.einsum(
                    'bnj,kj->bnk', placed, R_i)
                seq_out[start_i:end_i] = seq_out[:subunit_len]
            coords_out = coords_out - P[None, None, :]
        else:
            # Whole-assembly mode: pure rotation around origin, no centering.
            for i in range(self.order):
                start_i = subunit_len * i
                end_i = subunit_len * (i + 1)
                coords_out[start_i:end_i] = torch.einsum(
                    'bnj,kj->bnk', coords_out[:subunit_len], self.sym_rots[i])
                seq_out[start_i:end_i] = seq_out[:subunit_len]
        return coords_out, seq_out

    def close_neighbors(self):
        """close_neighbors finds the rotations within self.sym_rots that
        correspond to close neighbors.

        Returns:
            list of rotation matrices corresponding to the identity and close neighbors
        """
        # set of small rotation angle rotations
        rel_rot = lambda M: np.linalg.norm(Rotation.from_matrix(M).as_rotvec())
        rel_rots = [(i+1, rel_rot(M)) for i, M in enumerate(self.sym_rots[1:])]
        min_rot = min(rel_rot_val[1] for rel_rot_val in rel_rots)
        close_rots = [np.eye(3)] + [
                self.sym_rots[i] for i, rel_rot_val in rel_rots if
                np.isclose(rel_rot_val, min_rot)
                ]
        return close_rots
